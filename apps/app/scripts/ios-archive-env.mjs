import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  projectEnv,
  validateEnv,
  validateProductionEnv,
} from '../../../scripts/env/lib.mjs';
import { resolveValues } from '../../../scripts/env/sources.mjs';

const GENERATED_START = '# >>> zap-engine production Expo env >>>';
const GENERATED_END = '# <<< zap-engine production Expo env <<<';

function shellQuote(value) {
  return `'${String(value).replaceAll("'", `'"'"'`)}'`;
}

function stripGeneratedBlock(contents) {
  const start = contents.indexOf(GENERATED_START);
  if (start === -1) return contents.trimEnd();

  const end = contents.indexOf(GENERATED_END, start);
  if (end === -1) {
    return contents.slice(0, start).trimEnd();
  }

  return `${contents.slice(0, start)}${contents.slice(end + GENERATED_END.length)}`.trimEnd();
}

export function buildIosArchiveEnv(canonicalEnv) {
  const validation = validateEnv(canonicalEnv, { target: 'expo' });
  const productionErrors = validateProductionEnv(canonicalEnv);
  const errors = [...validation.errors, ...productionErrors];

  if (errors.length > 0) {
    throw new Error(
      [
        'Production Expo environment is not valid for an iOS archive:',
        ...errors.map((error) => `  - ${error}`),
      ].join('\n'),
    );
  }

  const projected = projectEnv(canonicalEnv, 'expo');
  const requiredProjected = [
    'EXPO_PUBLIC_PRIVY_APP_ID',
    'EXPO_PUBLIC_PRIVY_CLIENT_ID',
  ];
  const missing = requiredProjected.filter((name) => !projected[name]?.trim());

  if (missing.length > 0) {
    throw new Error(
      `Production Expo environment is missing ${missing.join(', ')}. ` +
        'Sync/fix the canonical PRIVY_MOBILE_* values in Infisical before archiving.',
    );
  }

  return {
    ...projected,
    // Local Xcode archives should evaluate app.config.ts like the EAS production
    // profile so store builds do not include expo-dev-client configuration.
    EAS_BUILD_PROFILE: 'production',
  };
}

export function loadIosArchiveEnv() {
  return buildIosArchiveEnv(resolveValues('prod'));
}

export function renderIosArchiveXcodeEnv(existingContents, archiveEnv) {
  const existing = stripGeneratedBlock(existingContents);
  const generated = [
    GENERATED_START,
    '# Generated by `pnpm --filter @zapengine/app ios:archive`.',
    '# Do not edit these values in Xcode; Infisical prod is the source of truth.',
    ...Object.entries(archiveEnv)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([name, value]) => `export ${name}=${shellQuote(value)}`),
    GENERATED_END,
  ].join('\n');

  return existing ? `${existing}\n\n${generated}\n` : `${generated}\n`;
}

export function writeIosArchiveXcodeEnv(appRoot, archiveEnv) {
  const path = join(appRoot, 'ios', '.xcode.env.local');
  const existing = existsSync(path) ? readFileSync(path, 'utf8') : '';
  writeFileSync(path, renderIosArchiveXcodeEnv(existing, archiveEnv), {
    mode: 0o600,
  });
  return path;
}
